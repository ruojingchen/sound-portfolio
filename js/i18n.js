  let lang = localStorage.getItem("crj-lang") || "zh";

  function t(key) {
    return (DICT[lang] && DICT[lang][key]) || DICT.zh[key] || key;
  }

  function getProject(id) {
    return PROJECTS[lang][id] || PROJECTS.zh[id];
  }

  function apply(root = document) {
    root.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      const val = t(key);
      if (val != null) el.textContent = val;
    });
    root.querySelectorAll("[data-i18n-html]").forEach((el) => {
      const key = el.getAttribute("data-i18n-html");
      const val = t(key);
      if (val != null) el.innerHTML = val;
    });
    root.querySelectorAll("[data-i18n-aria]").forEach((el) => {
      const key = el.getAttribute("data-i18n-aria");
      const val = t(key);
      if (val != null) el.setAttribute("aria-label", val);
    });

    document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";
    document.title = t("meta.title");
    document.body.dataset.lang = lang;

    document.querySelectorAll(".lang-switch__btn").forEach((btn) => {
      const active = btn.dataset.lang === lang;
      btn.classList.toggle("is-active", active);
      btn.setAttribute("aria-pressed", active ? "true" : "false");
    });

    document.querySelectorAll(".project:not(.is-hidden)").forEach((p) => {
      p.style.maxHeight = `${p.scrollHeight}px`;
    });

    window.dispatchEvent(new CustomEvent("crj:langchange", { detail: { lang } }));
  }

  function setLang(next) {
    if (!DICT[next] || next === lang) return;
    lang = next;
    localStorage.setItem("crj-lang", lang);
    apply();
  }

  function getLang() {
    return lang;
  }

  function bindSwitcher() {
    document.querySelectorAll(".lang-switch__btn").forEach((btn) => {
      btn.addEventListener("click", () => setLang(btn.dataset.lang));
    });
  }

  return { t, apply, setLang, getLang, getProject, bindSwitcher };
